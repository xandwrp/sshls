pub fn generate_config(inventory: &Inventory) -> String {
    let mut output = String::from("# Generated by sshls. Do not edit.\n");
    for host in &inventory.hosts {
        output.push('\n');
        output.push_str("Host ");
        output.push_str(&host.name);
        output.push('\n');
        output.push_str("    HostName ");
        output.push_str(&host.hostname);
        output.push('\n');
        if let Some(user) = &host.user {
            output.push_str("    User ");
            output.push_str(user);
            output.push('\n');
        }
        if let Some(port) = host.port {
            output.push_str("    Port ");
            output.push_str(&port.to_string());
            output.push('\n');
        }
        if let Some(identity) = &host.identity_file {
            output.push_str("    IdentityFile ");
            output.push_str(&quote_identity(identity));
            output.push('\n');
        }
    }
    output
}

pub fn resolve(paths: &AppPaths, name: &str) -> Result<()> {
    validate_name(name)?;
    let status = ssh_command(paths)
        .arg("-G")
        .arg(name)
        .stdin(Stdio::null())
        .status()
        .with_context(|| format!("running {}", paths.ssh_binary.display()))?;
    if !status.success() {
        bail!("SSH resolution failed with {status}");
    }
    Ok(())
}

pub fn test_connection(paths: &AppPaths, name: &str, timeout_seconds: u64) -> Result<()> {
    validate_name(name)?;
    let mut command = ssh_command(paths);
    let mut child = command
        .args([
            "-o",
            "BatchMode=yes",
            "-o",
            "NumberOfPasswordPrompts=0",
            "-o",
            &format!("ConnectTimeout={timeout_seconds}"),
            "-o",
            "StrictHostKeyChecking=yes",
            "-o",
            "UpdateHostKeys=no",
            "-o",
            "ControlMaster=no",
            "-o",
            "ControlPath=none",
        ])
        .arg(name)
        .arg("exit")
        .stdin(Stdio::null())
        .spawn()
        .with_context(|| format!("running {}", paths.ssh_binary.display()))?;

    match child
        .wait_timeout(Duration::from_secs(timeout_seconds))
        .context("waiting for SSH")?
    {
        Some(status) if status.success() => {
            println!("Connection to {name} succeeded.");
            Ok(())
        }
        Some(status) => bail!("SSH test failed with {status}"),
        None => {
            child.kill().context("terminating timed-out SSH process")?;
            child.wait().context("reaping timed-out SSH process")?;
            bail!("SSH test timed out after {timeout_seconds} seconds")
        }
    }
}

#[derive(Debug, Default)]
pub struct CheckReport {
    checks: Vec<Check>,
}

#[derive(Debug)]
struct Check {
    outcome: Outcome,
    message: String,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Outcome {
    Ok,
    Error,
}

impl CheckReport {
    pub fn is_ok(&self) -> bool {
        !self
            .checks
            .iter()
            .any(|check| check.outcome == Outcome::Error)
    }

    pub fn print(&self) {
        for check in &self.checks {
            let label = match check.outcome {
                Outcome::Ok => "OK",
                Outcome::Error => "ERROR",
            };
            println!("{label:<5} {}", check.message);
        }
    }

    fn ok(&mut self, message: impl Into<String>) {
        self.checks.push(Check {
            outcome: Outcome::Ok,
            message: message.into(),
        });
    }

    fn error(&mut self, message: impl Into<String>) {
        self.checks.push(Check {
            outcome: Outcome::Error,
            message: message.into(),
        });
    }
}

pub fn check_config(store: &Store, paths: &AppPaths) -> CheckReport {
    let mut report = CheckReport::default();
    let inventory = match store.load() {
        Ok(inventory) => {
            report.ok(format!(
                "inventory is valid ({} destination{})",
                inventory.hosts.len(),
                if inventory.hosts.len() == 1 { "" } else { "s" }
            ));
            inventory
        }
        Err(error) => {
            report.error(format!("inventory is invalid: {error:#}"));
            return report;
        }
    };

    check_generated(&mut report, &inventory, paths);
    check_include(&mut report, paths);
    check_identities(&mut report, &inventory, paths);

    if check_ssh_binary(&mut report, paths) {
        for host in &inventory.hosts {
            check_resolution(&mut report, host, paths);
        }
    }
    report
}

fn check_generated(report: &mut CheckReport, inventory: &Inventory, paths: &AppPaths) {
    let expected = generate_config(inventory);
    match fs::read_to_string(&paths.generated_config) {
        Ok(actual) if actual == expected => report.ok("generated config is current"),
        Ok(_) => report.error(format!(
            "generated config is stale; run `sshls config sync` ({})",
            paths.generated_config.display()
        )),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => report.error(format!(
            "generated config is missing; run `sshls config sync` ({})",
            paths.generated_config.display()
        )),
        Err(error) => report.error(format!(
            "cannot read generated config {}: {error}",
            paths.generated_config.display()
        )),
    }
}

fn check_include(report: &mut CheckReport, paths: &AppPaths) {
    match paths.user_config_has_include() {
        Ok(true) => report.ok("user SSH config includes the generated config"),
        Ok(false) => report.error(format!(
            "add `{}` to {}",
            paths.include_directive(),
            paths.user_config.display()
        )),
        Err(error) => report.error(format!("cannot check SSH include: {error:#}")),
    }
}

fn check_identities(report: &mut CheckReport, inventory: &Inventory, paths: &AppPaths) {
    let mut missing = 0usize;
    for host in &inventory.hosts {
        if let Some(identity) = &host.identity_file {
            let expanded = paths.expand_identity(identity);
            if !expanded.is_file() {
                missing += 1;
                report.error(format!(
                    "identity for {} does not exist: {}",
                    host.name,
                    expanded.display()
                ));
            }
        }
    }
    if missing == 0 {
        report.ok("all referenced identity files exist");
    }
}

fn check_ssh_binary(report: &mut CheckReport, paths: &AppPaths) -> bool {
    let mut command = Command::new(&paths.ssh_binary);
    command
        .arg("-V")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    match run_status_with_timeout(&mut command, Duration::from_secs(5)) {
        Ok(status) if status.success() => {
            report.ok(format!(
                "SSH client is available ({})",
                paths.ssh_binary.display()
            ));
            true
        }
        Ok(status) => {
            report.error(format!(
                "SSH client version check failed with {status} ({})",
                paths.ssh_binary.display()
            ));
            false
        }
        Err(error) => {
            report.error(format!(
                "SSH client is unavailable at {}: {error}",
                paths.ssh_binary.display()
            ));
            false
        }
    }
}

fn check_resolution(report: &mut CheckReport, host: &Host, paths: &AppPaths) {
    let mut command = ssh_command(paths);
    command.arg("-G").arg(&host.name).stdin(Stdio::null());
    let output = match run_output_with_timeout(&mut command, Duration::from_secs(5)) {
        Ok(output) if output.status.success() => output,
        Ok(output) => {
            report.error(format!(
                "SSH cannot resolve {}: {}",
                host.name,
                String::from_utf8_lossy(&output.stderr).trim()
            ));
            return;
        }
        Err(error) => {
            report.error(format!("SSH cannot resolve {}: {error}", host.name));
            return;
        }
    };

    let resolved = parse_ssh_g(&String::from_utf8_lossy(&output.stdout));
    let mut mismatches = Vec::new();
    compare_value(&mut mismatches, &resolved, "hostname", &host.hostname);
    if let Some(user) = &host.user {
        compare_value(&mut mismatches, &resolved, "user", user);
    }
    if let Some(port) = host.port {
        compare_value(&mut mismatches, &resolved, "port", &port.to_string());
    }

    if mismatches.is_empty() {
        report.ok(format!("SSH resolves {} as managed", host.name));
    } else {
        report.error(format!(
            "SSH resolution for {} differs: {}",
            host.name,
            mismatches.join(", ")
        ));
    }

    if let Some(identity) = &host.identity_file {
        let expected_literal = normalize_path_text(identity);
        let expected_expanded =
            normalize_path_text(&paths.expand_identity(identity).to_string_lossy());
        let active = resolved.get("identityfile").is_some_and(|values| {
            values.iter().any(|value| {
                let actual = normalize_path_text(value);
                actual.eq_ignore_ascii_case(&expected_literal)
                    || actual.eq_ignore_ascii_case(&expected_expanded)
            })
        });
        if !active {
            report.error(format!(
                "SSH resolution for {} does not include managed identity {:?}",
                host.name, identity
            ));
        }
    }
}

fn compare_value(
    mismatches: &mut Vec<String>,
    resolved: &HashMap<String, Vec<String>>,
    key: &str,
    expected: &str,
) {
    let actual = resolved.get(key).and_then(|values| values.first());
    if !actual.is_some_and(|actual| actual.eq_ignore_ascii_case(expected)) {
        mismatches.push(format!(
            "{key} expected {expected:?}, got {}",
            actual.map_or("<missing>", String::as_str)
        ));
    }
}

fn parse_ssh_g(output: &str) -> HashMap<String, Vec<String>> {
    let mut values: HashMap<String, Vec<String>> = HashMap::new();
    for line in output.lines() {
        if let Some((key, value)) = line.split_once(char::is_whitespace) {
            values
                .entry(key.to_ascii_lowercase())
                .or_default()
                .push(value.trim().to_owned());
        }
    }
    values
}

fn quote_identity(identity: &str) -> String {
    let normalized = if cfg!(windows) {
        identity.replace('\\', "/")
    } else {
        identity.to_owned()
    };
    if normalized.chars().any(char::is_whitespace) || normalized.contains('#') {
        format!("\"{normalized}\"")
    } else {
        normalized
    }
}

fn normalize_path_text(value: &str) -> String {
    value.trim_matches('"').replace('\\', "/")
}

fn ssh_command(paths: &AppPaths) -> Command {
    let mut command = Command::new(&paths.ssh_binary);
    if let Some(config) = &paths.ssh_config_override {
        command.arg("-F").arg(config);
    }
    command
}

fn run_status_with_timeout(command: &mut Command, timeout: Duration) -> Result<ExitStatus> {
    let mut child = command.spawn().context("starting process")?;
    match child.wait_timeout(timeout).context("waiting for process")? {
        Some(status) => Ok(status),
        None => {
            child.kill().context("terminating timed-out process")?;
            child.wait().context("reaping timed-out process")?;
            bail!("process timed out after {} seconds", timeout.as_secs())
        }
    }
}

fn run_output_with_timeout(command: &mut Command, timeout: Duration) -> Result<Output> {
    let mut stdout_file = tempfile::tempfile().context("creating stdout capture")?;
    let mut stderr_file = tempfile::tempfile().context("creating stderr capture")?;
    command
        .stdout(Stdio::from(
            stdout_file.try_clone().context("cloning stdout capture")?,
        ))
        .stderr(Stdio::from(
            stderr_file.try_clone().context("cloning stderr capture")?,
        ));
    let status = run_status_with_timeout(command, timeout)?;

    let mut stdout = Vec::new();
    stdout_file
        .seek(SeekFrom::Start(0))
        .and_then(|_| stdout_file.read_to_end(&mut stdout))
        .context("reading captured stdout")?;
    let mut stderr = Vec::new();
    stderr_file
        .seek(SeekFrom::Start(0))
        .and_then(|_| stderr_file.read_to_end(&mut stderr))
        .context("reading captured stderr")?;
    Ok(Output {
        status,
        stdout,
        stderr,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_is_stable_and_minimal() {
        let inventory = Inventory {
            version: 1,
            hosts: vec![Host {
                name: "prod".into(),
                hostname: "example.com".into(),
                user: Some("deploy".into()),
                port: Some(2222),
                identity_file: Some("~/.ssh/id prod".into()),
                tags: vec!["ignored".into()],
            }],
        };
        assert_eq!(
            generate_config(&inventory),
            "# Generated by sshls. Do not edit.\n\nHost prod\n    HostName example.com\n    User deploy\n    Port 2222\n    IdentityFile \"~/.ssh/id prod\"\n"
        );
    }

    #[test]
    fn parses_repeated_ssh_values() {
        let values = parse_ssh_g(
            "host prod\nhostname example.com\nidentityfile ~/.ssh/one\nidentityfile ~/.ssh/two\n",
        );
        assert_eq!(values["hostname"], ["example.com"]);
        assert_eq!(values["identityfile"].len(), 2);
    }
}
